import AppKit
import SwiftUI

/// Hosts the engine's preview layer, which shows exactly the frames being recorded.
struct PreviewView: NSViewRepresentable {
    let layer: CALayer

    func makeNSView(context: Context) -> NSView {
        let view = NSView()
        view.layer = layer
        view.wantsLayer = true
        return view
    }

    func updateNSView(_ nsView: NSView, context: Context) {}
}
